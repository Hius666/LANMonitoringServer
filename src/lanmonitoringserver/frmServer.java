    private void btnStartServerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStartServerActionPerformed
        // TODO add your handling code here:
        String portStr = txtPort.getText().trim();
        if (portStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập Port Server!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int port = Integer.parseInt(portStr);
            serverSocket = new ServerSocket(port);
            isRunning = true;
            
            lblServerStatus.setText("● Đang chạy (Port: " + port + ")");
            btnStartServer.setEnabled(false);
            btnStopServer.setEnabled(true);
            txtPort.setEnabled(false);
            
            log("Server started at " + txtServerIP.getText() + ":" + port);
            
            // Luồng lắng nghe các kết nối Client đến
            clientThreadPool = Executors.newCachedThreadPool();
            clientThreadPool.execute(new ServerAcceptTask());
            
            // Khởi động luồng kiểm tra timeout (10 giây không có heartbeat -> Offline)
            startTimeoutChecker();
            
        } catch (Exception e) {
            log("Không thể khởi động Server: " + e.getMessage());
            JOptionPane.showMessageDialog(this, "Lỗi khởi động: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnStartServerActionPerformed

