    private void btnSendMessageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendMessageActionPerformed
        // TODO add your handling code here:
        String selectedClient = (String) cboClient.getSelectedItem();
        String message = txtMessage.getText().trim();
        
        if (selectedClient == null || selectedClient.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Chưa chọn Client nhận thông điệp!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (message.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập nội dung thông điệp!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Tìm client trong danh sách dựa theo Hostname hoặc ID
        ClientInfo targetClient = null;
        for (ClientInfo c : clientMap.values()) {
            if (c.hostname.equals(selectedClient) || c.id.equals(selectedClient)) {
                targetClient = c;
                break;
            }
        }
        
        if (targetClient != null && targetClient.out != null) {
            targetClient.out.println("MESSAGE|" + message);
            lblAck.setText("Đã gửi message tới " + targetClient.hostname + ", chờ ACK...");
            log("Đã gửi message tới " + targetClient.hostname + ": " + message);
        } else {
            JOptionPane.showMessageDialog(this, "Client này hiện không ONLINE hoặc đã mất kết nối!", "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSendMessageActionPerformed
    
    private void stopServer() {
        isRunning = false;
        try {
            if (serverSocket != null) serverSocket.close();
            if (clientThreadPool != null) clientThreadPool.shutdownNow();
            if (timeoutChecker != null) timeoutChecker.shutdownNow();
        } catch (Exception e) {}
        
        // Đóng toàn bộ kết nối các client đang mở
        for (ClientInfo client : clientMap.values()) {
            try {
                if (client.out != null) client.out.close();
            } catch (Exception ex) {}
        }
        clientMap.clear();
        
        SwingUtilities.invokeLater(() -> {
            lblServerStatus.setText("● Đã dừng");
            btnStartServer.setEnabled(true);
            btnStopServer.setEnabled(false);
            txtPort.setEnabled(true);
            tableModel.setRowCount(0);
            updateClientStatsDisplay();
            log("Server đã dừng hoạt động.");
        });
    }
    
    // Luồng chấp nhận kết nối từ nhiều Client (Multi-client)
    private class ServerAcceptTask implements Runnable {
        @Override
        public void run() {
            while (isRunning) {
                try {
                    Socket clientSocket = serverSocket.accept();
                    new Thread(new ClientHandler(clientSocket)).start();
                } catch (Exception e) {
                    if (!isRunning) break;
                }
            }
        }
    }

    // Luồng xử lý riêng cho từng Client kết nối tới
    private class ClientHandler implements Runnable {
        private Socket socket;
        private BufferedReader in;
        private PrintWriter out;
        private String currentClientID;

        public ClientHandler(Socket socket) {
            this.socket = socket;
        }

        @Override
        public void run() {
            try {
                in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
                out = new PrintWriter(socket.getOutputStream(), true);
                
                String line;
                while ((line = in.readLine()) != null) {
                    String[] parts = line.split("\\|");
                    String cmd = parts[0];
                    
                    if (cmd.equals("CONNECT")) {
                        // Cấu trúc: CONNECT|ID|Hostname|IP
                        currentClientID = parts[1];
                        String hostname = parts[2];
                        String ip = parts[3];
                        
                        ClientInfo info = new ClientInfo(currentClientID, hostname, ip, out);
                        clientMap.put(currentClientID, info);
                        
                        log("Client connected: " + hostname + " (" + ip + ")");
                        updateServerGUI();
                        
                    } else if (cmd.equals("HEARTBEAT")) {
                        // Cấu trúc: HEARTBEAT|ID|CPU|RAM
                        currentClientID = parts[1];
                        double cpu = Double.parseDouble(parts[2]);
                        double ram = Double.parseDouble(parts[3]);
                        
                        ClientInfo info = clientMap.get(currentClientID);
                        if (info != null) {
                            info.status = "ONLINE";
                            info.cpu = String.format("%.1f%%", cpu);
                            info.ram = String.format("%.1f%%", ram);
                            info.lastSeenTime = System.currentTimeMillis();
                            info.out = out;
                            updateServerGUI();
                        }
                        
                    } else if (cmd.equals("ACK")) {
                        // Cấu trúc: ACK|ID|MESSAGE_RECEIVED
                        String id = parts[1];
                        ClientInfo info = clientMap.get(id);
                        String name = (info != null) ? info.hostname : id;
                        
                        SwingUtilities.invokeLater(() -> {
                            lblAck.setText("✓ " + name + " đã nhận thông điệp (ACK)");
                            log("Nhận phản hồi ACK từ " + name);
                        });
                    }
                }
            } catch (Exception e) {
                // Mất kết nối
                if (currentClientID != null && clientMap.containsKey(currentClientID)) {
                    ClientInfo info = clientMap.get(currentClientID);
                    log("Client mất kết nối đột ngột: " + info.hostname);
                    info.status = "OFFLINE";
                    updateServerGUI();
                }
            }
        }
    }

    // Luồng quét mỗi 3 giây: Nếu quá 10 giây không có Heartbeat -> Chuyển sang OFFLINE
    private void startTimeoutChecker() {
        timeoutChecker = Executors.newScheduledThreadPool(1);
        timeoutChecker.scheduleAtFixedRate(() -> {
            if (!isRunning) return;
            long now = System.currentTimeMillis();
            boolean changed = false;
            
            for (ClientInfo info : clientMap.values()) {
                if (info.status.equals("ONLINE") && (now - info.lastSeenTime > 10000)) {
                    info.status = "OFFLINE";
                    info.cpu = "---";
                    info.ram = "---";
                    info.responseTime = "---";
                    log("Phát hiện timeout (>10s), chuyển " + info.hostname + " sang trạng thái OFFLINE");
                    changed = true;
                }
            }
            if (changed) {
                updateServerGUI();
            }
        }, 0, 3, TimeUnit.SECONDS);
    }

    // Cập nhật lại JTable và ComboBox danh sách Client trên giao diện Server
    private void updateServerGUI() {
        SwingUtilities.invokeLater(() -> {
            tableModel.setRowCount(0);
            cboClient.removeAllItems();
            
            int onlineCount = 0;
            int offlineCount = 0;
            
            int index = 1;
            for (ClientInfo info : clientMap.values()) {
                tableModel.addRow(new Object[]{
                    String.format("%02d", index++),
                    info.hostname,
                    info.ip,
                    info.status,
                    info.responseTime,
                    info.cpu,
                    info.ram,
                    LocalTime.ofNanoOfDay(info.lastSeenTime % 86400000L * 1000000L).withNano(0).toString()
                });
                
                if (info.status.equals("ONLINE")) {
                    onlineCount++;
                    cboClient.addItem(info.hostname); // Chỉ đưa các máy Online vào ComboBox nhận tin nhắn
                } else {
                    offlineCount++;
                }
            }
            
            lblTotalClients.setText(String.valueOf(clientMap.size()));
            lblOnline.setText(String.valueOf(onlineCount));
            lblOffline.setText(String.valueOf(offlineCount));
        });
    }

    private void updateClientStatsDisplay() {
        lblTotalClients.setText("0");
        lblOnline.setText("0");
        lblOffline.setText("0");
    }
    
